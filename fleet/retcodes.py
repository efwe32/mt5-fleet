OK_RETCODES = {10008, 10009, 10010}


def trade_msg(retcode: int, comment: str = "") -> str:
    base = TRADE_RETCODES.get(int(retcode), f"未知返回码 {retcode}")
    extra = f"（终端原文：{comment}）" if comment and comment not in base else ""
    return f"[{retcode}] {base}{extra}"


def error_msg(err) -> str:
    try:
        code, text = err
    except Exception:
        return str(err)
    zh = LAST_ERRORS.get(int(code))
    return f"[{code}] {zh}（终端原文：{text}）" if zh else f"[{code}] 终端返回：{text}"
